/**
 * Очищает название города/региона и пытается найти его координаты в локальной базе
 * @param {string} rawLocation 
 * @returns {{ lat: number, lon: number, matchedName: string } | null}
 */
export function resolveCityCoordinates(rawLocation) {
  if (!rawLocation || typeof rawLocation !== 'string') return null;

  // Очищаем от мусора: "г. ", "резерв", почтовых индексов, "и ещё N рег."
  const clean = rawLocation
    .toLowerCase()
    .replace(/резерв/gi, '')
    .replace(/и ещё.*/gi, '')
    .replace(/г\.|город|обл\.|область|край|респ\.|республика|район|р-н|пос\.|п\.|пгт|с\.|село|д\.|дер\./gi, '')
    .replace(/\b\d{6}\b/g, '') // убираем индексы
    .replace(/[,\.;\-]/g, ' ')
    .trim();

  // 1. Прямое совпадение очищенной строки
  if (CITY_COORDINATES[clean]) {
    const [lat, lon] = CITY_COORDINATES[clean];
    return { lat, lon, matchedName: clean };
  }

  // 2. Поиск по отдельным словам/токенам
  const tokens = clean.split(/\s+/).filter(t => t.length > 2);
  for (const token of tokens) {
    if (CITY_COORDINATES[token]) {
      const [lat, lon] = CITY_COORDINATES[token];
      return { lat, lon, matchedName: token };
    }
  }

  // 3. Поиск подстроки в ключах словаря
  for (const [key, coords] of Object.entries(CITY_COORDINATES)) {
    if (clean.includes(key) || rawLocation.toLowerCase().includes(key)) {
      return { lat: coords[0], lon: coords[1], matchedName: key };
    }
  }

  return null;
}
